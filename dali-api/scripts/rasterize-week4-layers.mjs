// Turns the week 4 demo-expo layer SVGs into WebP sprites cropped to what each one draws, and
// writes their boxes to week4Sprites.ts. Full-frame vector layers were 14 screen-sized compositor
// layers re-rasterising embedded bitmaps; cropped bitmaps are a fraction of the memory and work.
//
// Rendering goes through Chrome so the SVGs' pattern fills come out exactly as the browser draws
// them. One sprite per layer: the grouping and paint order stay week4Layers.ts's.
//
//   node scripts/rasterize-week4-layers.mjs <dir of layer SVGs> [scale=1] [quality=0.8]
//
// Needs Google Chrome installed (Playwright's `chrome` channel).

import fs from 'node:fs'
import path from 'node:path'
import { chromium } from 'playwright'

const [srcDir, scaleArg = '1', qualityArg = '0.8'] = process.argv.slice(2)
if (!srcDir) {
  console.error('usage: node scripts/rasterize-week4-layers.mjs <svg dir> [scale] [quality]')
  process.exit(1)
}
const scale = Number(scaleArg)
const quality = Number(qualityArg)
const FRAME_W = 4075
const FRAME_H = 1545

const root = path.resolve(import.meta.dirname, '..')
const outDir = path.join(root, 'app/assets/landing/week4/layers')
const manifest = fs.readFileSync(
  path.join(root, 'app/components/home/landing/backgrounds/week4/week4Layers.ts'),
  'utf8',
)
const names = [...manifest.matchAll(/name: '([^']+)'/g)].map((m) => m[1])

const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage()
const boxes = []

for (const name of names) {
  const svg = fs.readFileSync(path.join(srcDir, `${name}.svg`))
  const src = `data:image/svg+xml;base64,${svg.toString('base64')}`
  const { box, data } = await page.evaluate(
    async ({ src, w, h, scale, quality }) => {
      const img = new Image()
      img.src = src
      await img.decode()
      const full = document.createElement('canvas')
      full.width = Math.round(w * scale)
      full.height = Math.round(h * scale)
      const ctx = full.getContext('2d')
      ctx.drawImage(img, 0, 0, full.width, full.height)
      const { data: px } = ctx.getImageData(0, 0, full.width, full.height)
      let x0 = full.width, y0 = full.height, x1 = -1, y1 = -1
      for (let y = 0; y < full.height; y++) {
        for (let x = 0; x < full.width; x++) {
          if (px[(y * full.width + x) * 4 + 3] === 0) continue
          if (x < x0) x0 = x
          if (x > x1) x1 = x
          if (y < y0) y0 = y
          if (y > y1) y1 = y
        }
      }
      const crop = document.createElement('canvas')
      crop.width = x1 - x0 + 1
      crop.height = y1 - y0 + 1
      crop.getContext('2d').drawImage(full, -x0, -y0)
      return {
        // Back in frame units, so the scene places sprites the same at any raster scale.
        box: { x: x0 / scale, y: y0 / scale, w: crop.width / scale, h: crop.height / scale },
        data: crop.toDataURL('image/webp', quality).split(',')[1],
      }
    },
    { src, w: FRAME_W, h: FRAME_H, scale, quality },
  )
  fs.writeFileSync(path.join(outDir, `${name}.webp`), Buffer.from(data, 'base64'))
  boxes.push({ name, ...box })
  console.log(name, box, `${Math.round(Buffer.from(data, 'base64').length / 1024)} KB`)
}
await browser.close()

const round = (n) => Math.round(n * 100) / 100
fs.writeFileSync(
  path.join(root, 'app/components/home/landing/backgrounds/week4/week4Sprites.ts'),
  `// Generated by scripts/rasterize-week4-layers.mjs. Do not edit by hand.

/** Where each layer's cropped sprite sits in the art's 4075x1545 frame, in frame units. */
export const WEEK4_SPRITES: Record<string, { x: number; y: number; w: number; h: number }> = {
${boxes.map((b) => `  '${b.name}': { x: ${round(b.x)}, y: ${round(b.y)}, w: ${round(b.w)}, h: ${round(b.h)} },`).join('\n')}
}
`,
)
